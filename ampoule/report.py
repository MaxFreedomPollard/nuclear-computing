    say(f"| the aperture as the GATE terminal | transistor/README.md | contrast {contrast:.2f} through 2 mm of tungsten"
        + (f" with plastic cells, {contrast_c:.2f} with CsI" if csi_line else "") + " |")
    say(f"| lead septa as inhibitory blocking | EMBODIMENT.md Section 1.2 | coupling reduced to {np.mean(blocked):.2f}, not cut |")
    say(f"| weights written by geometry | README, the scattering gate | nearest neighbour G ≈ {pow10(np.mean(az_nb))}, fan out {fan.mean():.1%} |")
    say(f"| shield sized with margin, dose to be certified | EMBODIMENT.md Section 1.5 | {dc:.3g} µSv/h at the wall, {d100:.3g} µSv/h at 1 m |")
    say("")
