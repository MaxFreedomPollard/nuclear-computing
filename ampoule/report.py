def figure(cur, mids, D, curve, G, Gsep, srcs, power, dc, d10, d100, ds, leak, spec, csi_point=None):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.colors import LogNorm
    INK, BLUE, RED, GREEN, AMBER, PURPLE, GREY = (
        "#16213e", "#2563eb", "#dc2626", "#16a34a", "#d97706", "#7c3aed", "#94a3b8")
    plt.rcParams.update({
        "figure.facecolor": "white", "axes.facecolor": "white", "savefig.facecolor": "white",
        "axes.edgecolor": INK, "axes.labelcolor": INK, "text.color": INK, "xtick.color": INK,
        "ytick.color": INK, "axes.titlecolor": INK, "font.size": 11, "axes.titlesize": 12,
        "axes.titleweight": "bold", "axes.grid": True, "grid.color": "#e5e7eb",
        "grid.linewidth": 0.8, "axes.spines.top": False, "axes.spines.right": False,
        "figure.dpi": 130, "svg.hashsalt": "nuclear-computer"})
    fig, ((A, B), (C, Dax)) = plt.subplots(2, 2, figsize=(13.4, 9.6))

    # A: spectra per second per keV
    def per_keV(y):
        edges = np.sqrt(mids[:-1] * mids[1:])
        w = np.diff(np.concatenate([[mids[0] ** 2 / edges[0]], edges, [mids[-1] ** 2 / edges[-1]]])) / 1e3
        return np.array(y) * D / np.maximum(w, 1e-30)
    A.plot(mids / 1e3, per_keV(cur), color=BLUE, lw=2.0, label="leaving the source capsule")
    A.plot(mids / 1e3, per_keV(spec * cur.sum()), color=AMBER, lw=1.6, ls="--", label="in a site (shape, scaled)")
    A.plot(mids / 1e3, per_keV(leak), color=RED, lw=1.8, label="escaping the shield")
    A.axvline(2280, color=GREY, ls=":", lw=1.2)
    A.set_xscale("log"); A.set_yscale("log")
    A.text(2150, A.get_ylim()[1] * 0.5, "⁹⁰Y endpoint", color=GREY, fontsize=8, ha="right", va="top")
    A.set_xlim(10, 3000); A.set_xlabel("photon energy (keV)"); A.set_ylabel("photons per second per keV")
    A.set_title("A.  The bremsstrahlung of 1 GBq of ⁹⁰Sr/⁹⁰Y, and what gets out")
    A.legend(frameon=False, fontsize=8.5, loc="lower left")

    # B: the collar transfer curve
    x = [f * 100 for f, _, _ in curve]; y = [m for _, m, _ in curve]; e = [s for _, _, s in curve]
    B.errorbar(x, y, yerr=e, fmt="-o", color=BLUE, lw=2.2, ms=6, capsize=3, label="mean site interaction rate, plastic cells")
    if csi_point:
        B.errorbar([100], [csi_point[0]], yerr=[csi_point[1]], fmt="D", color=AMBER, ms=7, capsize=3, label="CsI cells, collar open")
    B.axhline(1 / TAU_D, color=RED, ls="--", lw=1.3); B.text(2, 1 / TAU_D * 1.15, "pile up ceiling, 1/τ_d", color=RED, fontsize=8.5)
    B.axhline(1e6 / 64, color=AMBER, ls=":", lw=1.3); B.text(2, 1e6 / 64 * 1.15, "design proposal budget per site", color=AMBER, fontsize=8.5)
    B.set_yscale("log"); B.set_ylim(min(y) / 3, 3e7); B.set_xlim(-5, 108)
    B.set_xlabel("collar opening (percent of nominal)"); B.set_ylabel("interactions per second per site")
    B.set_title("B.  The GATE terminal: the tungsten collar's transfer curve")
    B.legend(frameon=False, fontsize=8.5, loc="lower right")

    # C: the Green's function
    Gp = np.maximum(G, 1e-6)
    im = C.imshow(Gp, norm=LogNorm(vmin=1e-5, vmax=max(Gp.max(), 1e-2)), cmap="Blues", origin="lower")
    for b in range(8, 64, 8):
        C.axhline(b - 0.5, color=GREY, lw=0.5); C.axvline(b - 0.5, color=GREY, lw=0.5)
    C.set_xlabel("photon born in site j (8 heights × 8 azimuths)"); C.set_ylabel("interacts in site k")
    C.set_title("C.  The synapse: G between the 64 sites")
    C.grid(False)
    plt.colorbar(im, ax=C, fraction=0.046, pad=0.03, label="G_kj per photon")

    # D: energy budget and dose
    labels = list(power); vals = [power[k] * 1e6 for k in labels]
    Dax.barh(range(len(labels)), vals, color=[GREY, AMBER, INK, BLUE, GREY, GREEN, PURPLE, RED], height=0.6)
    Dax.set_yticks(range(len(labels))); Dax.set_yticklabels([l.split(" (")[0] for l in labels], fontsize=8.5)
    Dax.set_xscale("log"); Dax.set_xlabel("deposited power (µW)")
    Dax.set_title("D.  Where the energy goes, and the dose outside")
    Dax.text(0.98, 0.96, f"ambient dose rate\nat the wall: {dc:.3g} µSv/h\nat 10 cm: {d10:.3g} µSv/h\nat 1 m: {d100:.3g} µSv/h",
             transform=Dax.transAxes, fontsize=9, ha="right", va="top", color=INK,
             bbox=dict(boxstyle="round", fc="white", ec=GREY))

    fig.suptitle("Figure 17.  The ampoule in real photon transport", fontsize=13, fontweight="bold", y=1.0)
    fig.tight_layout()
    for ext in ("svg", "png"):
        kw = {"metadata": {"Date": None}} if ext == "svg" else {}
        fig.savefig(os.path.join(FIGS, f"fig17_ampoule.{ext}"), bbox_inches="tight", **kw)
    plt.close(fig)
    print("wrote fig17_ampoule")


if __name__ == "__main__":
    main()
