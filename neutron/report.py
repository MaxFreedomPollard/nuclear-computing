def figure(curve, runs, P, spectra, edges, ts, Pt, Pinf, L, kpair):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    INK, BLUE, RED, GREEN, AMBER, PURPLE, GREY = (
        "#16213e", "#2563eb", "#dc2626", "#16a34a",
        "#d97706", "#7c3aed", "#94a3b8")
    plt.rcParams.update({
        "figure.facecolor": "white", "axes.facecolor": "white",
        "savefig.facecolor": "white", "axes.edgecolor": INK,
        "axes.labelcolor": INK, "text.color": INK, "xtick.color": INK,
        "ytick.color": INK, "axes.titlecolor": INK, "font.size": 11,
        "axes.titlesize": 12, "axes.titleweight": "bold",
        "axes.grid": True, "grid.color": "#e5e7eb", "grid.linewidth": 0.8,
        "axes.spines.top": False, "axes.spines.right": False,
        "figure.dpi": 130, "svg.hashsalt": "nuclear-computer",
    })
    fig, ((A, B), (C, D)) = plt.subplots(2, 2, figsize=(13.2, 9.4))

    # A: the transfer curve of the absorber, with a true gain axis on the right
    cd_pts = [(0, curve[0][1])] + [(int(n.split("cd")[1] or 100), k) for n, k, _ in curve[1:5]]
    x = [p[0] for p in cd_pts]; y = [p[1][0] for p in cd_pts]; e = [p[1][1] for p in cd_pts]
    A.errorbar(x, y, yerr=e, fmt="-o", color=BLUE, lw=2.2, ms=6, capsize=3,
               label="1 mm cadmium sheet")
    kb = curve[5][1]
    A.errorbar([100], [kb[0]], yerr=[kb[1]], fmt="s", color=PURPLE, ms=9, capsize=3,
               label="2 cm boron carbide blade")
    ka = runs["alone_A"]["k"]
    A.axhline(ka[0], color=GREY, ls=":", lw=1.3)
    A.text(50, ka[0] - 0.0009, "one tank alone: no neighbour to couple to",
           color=GREY, fontsize=8, va="top", ha="center")
    lo, hi = min(min(y), kb[0], ka[0]) - 0.004, max(y) + 0.004
    A.set_ylim(lo, hi)
    A.set_xlim(-6, 106)
    A.set_xlabel("absorber inserted between the tanks (percent)")
    A.set_ylabel("k of the pair")
    A.set_title("A.  The GATE terminal: an absorber between the tanks")
    A.legend(frameon=False, fontsize=8.5, loc="upper right")
    # the gain axis is the exact map k -> 1/(1-k), not a rescaled copy
    A2 = A.secondary_yaxis("right", functions=(lambda kk: 1.0 / (1.0 - np.clip(kk, None, 0.9999)),
                                               lambda MM: 1.0 - 1.0 / MM))
    A2.set_ylabel("gain M = 1/(1 − k)", color=AMBER)
    A2.tick_params(colors=AMBER)
    A.annotate(f"k = 1 is {(1-max(y))*1e5:.0f} pcm above the top of this axis:\nevery configuration is subcritical",
               xy=(0.03, 0.06), xycoords="axes fraction", fontsize=8, color=RED)

    # B: the drain, with the gain threshold
    labels = ["boron carbide\nblade in", "cadmium\nsheet in", "open"]
    keys = ["b4c", "cd", "open"]
    vals = [P[("cfA", k)][0][1] for k in keys]
    errs = [P[("cfA", k)][1][1] for k in keys]
    preds = [P[("cfA", k)][2][1] for k in keys]
    B.bar(range(3), vals, yerr=errs, color=[PURPLE, GREY, BLUE], width=0.6, capsize=4,
          label="transport (the drain)", zorder=3)
    B.plot(range(3), preds, "D", color=INK, ms=7, label="point model (I − K)⁻¹c", zorder=4)
    B.axhline(1.0, color=RED, ls="--", lw=1.3, zorder=2)
    B.text(-0.45, 1.03, "unity: one neutron out per neutron in", color=RED, fontsize=8.5,
           ha="left", va="bottom")
    B.set_ylim(0, max(max(vals), max(preds)) * 1.32)
    B.set_xticks(range(3)); B.set_xticklabels(labels, fontsize=9)
    B.set_xlabel("driver in tank A throughout")
    B.set_ylabel("fission neutrons born in B per driver neutron")
    B.set_title("B.  The DRAIN: gain across the gate, and its contrast")
    B.legend(frameon=False, fontsize=8.5, loc="upper left")
    B.annotate("", xy=(2, vals[2]), xytext=(0, vals[0]),
               arrowprops=dict(arrowstyle="<->", color=INK, lw=1.2, shrinkA=2, shrinkB=2))
    B.text(1.0, (vals[0] + vals[2]) / 2 * 1.06, f"ON/OFF contrast {vals[2]/vals[0]:.1f}",
           fontsize=9, ha="center", color=INK, fontweight="bold")

    # C: level restoration. The three outputs coincide, so draw them so that is visible.
    mid = np.sqrt(edges[:-1] * edges[1:])
    styles = [("cfA", BLUE, 5.0, 0.30, "driven from tank A (moderated input)"),
              ("cfB", PURPLE, 2.6, 0.95, "Cf-252 at the axis of B"),
              ("dtB", GREEN, 1.3, 1.00, "14.1 MeV at the axis of B")]
    for drive, c, lw, al, lab in styles:
        C.step(mid, spectra[drive][0], where="mid", color=c, lw=lw, alpha=al,
               label=f"born in B: {lab}", zorder=3)
    arr = spectra["cfA"][1]
    C.step(mid, arr * (spectra["cfA"][0].max() / max(arr.max(), 1e-30)), where="mid",
           color=AMBER, lw=1.6, ls="--", label="input: entering B through its wall (scaled)", zorder=2)
    for e_in, lab, frac, ha in ((2.13e6, "Cf-252 mean input\n2.13 MeV", 0.72, "right"),
                                (14.1e6, "14.1 MeV\ninput line", 0.50, "left")):
        C.axvline(e_in, color=GREY, ls=":", lw=1.2, zorder=1)
        pad = "  " if ha == "left" else ""
        C.text(e_in, spectra["cfA"][0].max() * frac, pad + lab, fontsize=7.6, color=GREY,
               ha=ha, va="center")
    C.set_xscale("log")
    C.set_xlabel("neutron energy (eV)")
    C.set_ylabel("spectrum per unit lethargy (normalised)")
    C.set_title("C.  Level restoration: three inputs, one output")
    C.legend(frameon=False, fontsize=7.8, loc="upper left")
    C.set_xlim(1e-3, 3e7)
    C.set_ylim(0, spectra["cfA"][0].max() * 1.35)
    C.annotate("the three output curves lie on top of one another:\nwhat is emitted does not remember what arrived",
               xy=(0.03, 0.02), xycoords="axes fraction", fontsize=8, color=INK)

    # D: step response
    D.plot(ts * 1e3, Pt[:, 0] / Pinf[0], color=GREY, lw=1.7, label="tank A production")
    D.plot(ts * 1e3, Pt[:, 1] / Pinf[1], color=BLUE, lw=2.4, label="tank B production (the drain)")
    D.axhline(1.0, color=GREY, ls=":", lw=1)
    M = 1 / (1 - kpair)
    D.set_xlabel("time after the driver in A switches on (ms)")
    D.set_ylabel("production, fraction of the steady state")
    D.set_title("D.  Switching: τ = Λ/(1 − k), and M/τ = 1/Λ")
    D.text(0.40, 0.30, f"Λ = {L*1e6:.0f} µs,  k = {kpair:.3f}\nτ = Λ/(1 − k) = {L*M*1e3:.2f} ms\n"
           f"M/τ = 1/Λ = {1/L/1e3:.0f} kHz", transform=D.transAxes, fontsize=9.5, color=INK)
    D.legend(frameon=False, fontsize=8.5, loc="lower right")

    fig.suptitle("Figure 15.  The neutron sector gate, computed from library data at k < 1",
                 fontsize=13, fontweight="bold", y=1.0)
    fig.tight_layout()
    for ext in ("svg", "png"):
        kw = {"metadata": {"Date": None}} if ext == "svg" else {}
        fig.savefig(os.path.join(FIGS, f"fig15_neutron_gate.{ext}"), bbox_inches="tight", **kw)
    plt.close(fig)
    print("wrote fig15_neutron_gate")


